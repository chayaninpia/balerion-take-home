package main

import (
	"testing"

	"github.com/shopspring/decimal"
)

func TestDecimalToBaht(t *testing.T) {
	tests := []struct {
		input    string
		expected string
	}{
		{"1234", "หนึ่งพันสองร้อยสามสิบสี่บาทถ้วน"},
		{"33333.75", "สามหมื่นสามพันสามร้อยสามสิบสามบาทเจ็ดสิบห้าสตางค์"},
		{"0", "ศูนย์บาทถ้วน"},
		{"0.00", "ศูนย์บาทถ้วน"},
		{"1", "หนึ่งบาทถ้วน"},
		{"5", "ห้าบาทถ้วน"},
		{"9", "เก้าบาทถ้วน"},
		{"10", "สิบบาทถ้วน"},
		{"11", "สิบเอ็ดบาทถ้วน"},
		{"20", "ยี่สิบบาทถ้วน"},
		{"21", "ยี่สิบเอ็ดบาทถ้วน"},
		{"30", "สามสิบบาทถ้วน"},
		{"31", "สามสิบเอ็ดบาทถ้วน"},
		{"99", "เก้าสิบเก้าบาทถ้วน"},
		{"100", "หนึ่งร้อยบาทถ้วน"},
		{"101", "หนึ่งร้อยเอ็ดบาทถ้วน"},
		{"111", "หนึ่งร้อยสิบเอ็ดบาทถ้วน"},
		{"121", "หนึ่งร้อยยี่สิบเอ็ดบาทถ้วน"},
		{"999", "เก้าร้อยเก้าสิบเก้าบาทถ้วน"},
		{"1000", "หนึ่งพันบาทถ้วน"},
		{"1001", "หนึ่งพันเอ็ดบาทถ้วน"},
		{"1010", "หนึ่งพันสิบบาทถ้วน"},
		{"1011", "หนึ่งพันสิบเอ็ดบาทถ้วน"},
		{"1111", "หนึ่งพันหนึ่งร้อยสิบเอ็ดบาทถ้วน"},
		{"9999", "เก้าพันเก้าร้อยเก้าสิบเก้าบาทถ้วน"},
		{"10000", "หนึ่งหมื่นบาทถ้วน"},
		{"11111", "หนึ่งหมื่นหนึ่งพันหนึ่งร้อยสิบเอ็ดบาทถ้วน"},
		{"99999", "เก้าหมื่นเก้าพันเก้าร้อยเก้าสิบเก้าบาทถ้วน"},
		{"100000", "หนึ่งแสนบาทถ้วน"},
		{"111111", "หนึ่งแสนหนึ่งหมื่นหนึ่งพันหนึ่งร้อยสิบเอ็ดบาทถ้วน"},
		{"999999", "เก้าแสนเก้าหมื่นเก้าพันเก้าร้อยเก้าสิบเก้าบาทถ้วน"},
		{"1000000", "หนึ่งล้านบาทถ้วน"},
		{"1234567", "หนึ่งล้านสองแสนสามหมื่นสี่พันห้าร้อยหกสิบเจ็ดบาทถ้วน"},
		{"0.01", "ศูนย์บาทหนึ่งสตางค์"},
		{"0.10", "ศูนย์บาทสิบสตางค์"},
		{"0.11", "ศูนย์บาทสิบเอ็ดสตางค์"},
		{"0.25", "ศูนย์บาทยี่สิบห้าสตางค์"},
		{"0.50", "ศูนย์บาทห้าสิบสตางค์"},
		{"0.99", "ศูนย์บาทเก้าสิบเก้าสตางค์"},
		{"1.01", "หนึ่งบาทหนึ่งสตางค์"},
		{"10.25", "สิบบาทยี่สิบห้าสตางค์"},
		{"100.50", "หนึ่งร้อยบาทห้าสิบสตางค์"},
		{"1.234", "หนึ่งบาทยี่สิบสามสตางค์"},
		{"1.235", "หนึ่งบาทยี่สิบสี่สตางค์"}, // 23.5 rounds to even 24
		{"1.245", "หนึ่งบาทยี่สิบสี่สตางค์"}, // 24.5 rounds to even 24
		{"1.255", "หนึ่งบาทยี่สิบหกสตางค์"},  // 25.5 rounds to even 26
		{"999999.99", "เก้าแสนเก้าหมื่นเก้าพันเก้าร้อยเก้าสิบเก้าบาทเก้าสิบเก้าสตางค์"},
	}

	for _, tt := range tests {
		t.Run(tt.input, func(t *testing.T) {
			d, err := decimal.NewFromString(tt.input)
			if err != nil {
				t.Fatalf("invalid test input %q: %v", tt.input, err)
			}
			got := DecimalToBaht(d)
			if got != tt.expected {
				t.Errorf("DecimalToBaht(%s) = %q, want %q", tt.input, got, tt.expected)
			}
		})
	}
}

func TestDecimalToBahtNegative(t *testing.T) {
	d := decimal.NewFromFloat(-100.50)
	result := DecimalToBaht(d)
	if result == "" {
		t.Error("DecimalToBaht should handle negative values")
	}
}
